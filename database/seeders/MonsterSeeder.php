    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        $this->command->info('Создание монстров...');

        $monsters = $this->getMonstersData();

        foreach ($monsters as $monsterData) {
            $monster = Monster::create([
                'name' => $monsterData['name'],
                'type' => $monsterData['type'],
                'level' => $monsterData['level'],
                'rank' => $monsterData['rank'],
                'faction_id' => null,
                'ai_behavior' => $monsterData['ai_behavior'],
                'respawn_time' => $monsterData['respawn_time'],
                'description' => $monsterData['description'],
                'is_active' => true,
            ]);

            MonsterStat::create([
                'monster_id' => $monster->id,
                'health_max' => $monsterData['stats']['health_max'],
                'mana_max' => $monsterData['stats']['mana_max'],
                'attack_power' => $monsterData['stats']['attack_power'],
                'magic_power' => $monsterData['stats']['magic_power'],
                'defense' => $monsterData['stats']['defense'],
                'magic_defense' => $monsterData['stats']['magic_defense'],
                'accuracy' => $monsterData['stats']['accuracy'],
                'magic_accuracy' => $monsterData['stats']['magic_accuracy'],
                'dodge' => $monsterData['stats']['dodge'],
                'critical_chance' => $monsterData['stats']['critical_chance'],
                'critical_power' => $monsterData['stats']['critical_power'],
                'experience_reward' => $monsterData['stats']['experience_reward'],
                'attack_type' => $monsterData['stats']['attack_type'],
            ]);
        }

        $this->command->info('Монстры успешно созданы!');
    }

