    /**
     * Генерировать статистики для монстра на основе уровня и типа.
     */
    private function generateStats(int $level, string $attackType, string $rank): array
    {
        $multiplier = match ($rank) {
            'normal' => 1.0,
            'elite' => 1.5,
            'boss' => 2.5,
            'world_boss' => 4.0,
            default => 1.0,
        };

        $baseHealth = 100 + ($level * 20);
        $baseMana = 50 + ($level * 10);
        $baseAttack = 10 + ($level * 3);
        $baseMagic = 5 + ($level * 2);
        $baseDefense = 5 + ($level * 2);
        $baseMagicDefense = 5 + ($level * 2);

        // Корректировка в зависимости от типа атаки
        if ($attackType === 'physical') {
            $baseMagic = (int) ($baseMagic * 0.5);
        } elseif ($attackType === 'magical') {
            $baseAttack = (int) ($baseAttack * 0.5);
        }

        return [
            'health_max' => (int) ($baseHealth * $multiplier),
            'mana_max' => (int) ($baseMana * $multiplier),
            'attack_power' => (int) ($baseAttack * $multiplier),
            'magic_power' => (int) ($baseMagic * $multiplier),
            'defense' => (int) ($baseDefense * $multiplier),
            'magic_defense' => (int) ($baseMagicDefense * $multiplier),
            'accuracy' => min(95.0, 60.0 + ($level * 2)),
            'magic_accuracy' => min(95.0, 60.0 + ($level * 2)),
            'dodge' => min(30.0, 5.0 + ($level * 1.5)),
            'critical_chance' => min(25.0, 5.0 + ($level * 0.8)),
            'critical_power' => 1.5 + ($level * 0.05),
            'experience_reward' => (int) (($level * 10) * $multiplier),
            'attack_type' => $attackType,
        ];
    }
